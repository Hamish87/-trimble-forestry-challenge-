"""Bundle the inspected scene images with their consumer for reliable delivery."""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
assets = root / "dist/assets/scenes"
images = {}
for path in sorted(assets.glob("*.webp")):
    data = path.read_bytes()
    if data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        raise ValueError(f"Invalid WebP: {path.name}")
    images[path.name] = "data:image/webp;base64," + base64.b64encode(data).decode("ascii")
if len(images) != 6:
    raise ValueError("Expected all six workflow illustrations")
source = (root / "src/scenes.js").read_text()
output = "// Generated by scripts/build-scene-images.py; edit src/scenes.js.\n"
output += "const SCENE_IMAGES=" + json.dumps(images, separators=(",", ":")) + ";\n"
(root / "dist/scenes.js").write_text(output + source)
print(f"Bundled {len(images)} workflow illustrations")
